import re
import warnings
from collections import defaultdict
from pathlib import Path

import numpy as np

from shekar.base import BaseTextTransform
from shekar.hub import resolve_model_path
from shekar.transliteration.byt5_decoder import ByT5Decoder
from shekar.transliteration.byt5_encoder import ByT5Encoder

# Sentence boundaries: whitespace after terminal punctuation, or any line break.
# The captured separator is kept so the original layout can be restored.
_SENTENCE_BREAK = re.compile(r"((?<=[.!?؟؛…])\s+|\s*\n\s*)")
_WHITESPACE = re.compile(r"(\s+)")
# The model degrades on long inputs (it starts repeating itself), so longer
# sentences are split at word boundaries into chunks of at most this size.
_MAX_CHUNK_BYTES = 200


def _chunk_words(sentence: str) -> list[str]:
    """Split a sentence into word-boundary chunks interleaved with separators."""
    if len(sentence.encode("utf-8")) <= _MAX_CHUNK_BYTES:
        return [sentence]
    tokens = _WHITESPACE.split(sentence)
    parts = [tokens[0]]
    for separator, word in zip(tokens[1::2], tokens[2::2]):
        joined = parts[-1] + separator + word
        if parts[-1] and len(joined.encode("utf-8")) > _MAX_CHUNK_BYTES:
            parts += [separator, word]
        else:
            parts[-1] = joined
    return parts


class ByT5Transliterator(BaseTextTransform):
    supports_batching = True

    def __init__(
        self,
        encoder_path: str | Path | None = None,
        decoder_path: str | Path | None = None,
        num_beams: int = 1,
        max_new_tokens: int | None = None,
        *,
        batch_size=32,
    ):
        """
        Args:
            max_new_tokens: Upper bound on generated byte tokens per sentence.
                ``None`` (default) derives it from the input length, so long
                sentences are never cut short.
        """
        self.batch_size = self._validate_batch_size(batch_size)
        self._direction = None  # to be set by subclasses
        ByT5Decoder.validate_generation_parameters(
            num_beams, 1 if max_new_tokens is None else max_new_tokens
        )

        encoder_path = resolve_model_path(encoder_path, "byt5_tg2fa_encoder_q8.onnx")
        decoder_path = resolve_model_path(decoder_path, "byt5_tg2fa_decoder_q8.onnx")

        self.encoder = ByT5Encoder(encoder_path)
        self.decoder = ByT5Decoder(decoder_path)
        self.num_beams = num_beams
        self.max_new_tokens = max_new_tokens

    def _function(self, X: str) -> str:
        return self._transform_batch([X], self.batch_size)[0]

    def transform(self, X):
        if isinstance(X, str):
            return self._function(X)
        # The existing iterable API returns a generator; retain its laziness.
        return self._iter_transliterations(X)

    def _iter_transliterations(self, texts):
        for batch in self._text_batches(texts, self.batch_size):
            yield from self._transform_batch(batch, self.batch_size)

    @staticmethod
    def _split_sentences(text: str) -> tuple[list[str], list[int]]:
        """Split text into short segments interleaved with their original separators.

        Segments are sentences, further split at word boundaries when long.
        Returns the pieces and the indices of the non-blank segments.
        """
        parts = []
        for i, piece in enumerate(_SENTENCE_BREAK.split(text.strip())):
            parts.extend([piece] if i % 2 else _chunk_words(piece))
        return parts, [i for i in range(0, len(parts), 2) if parts[i].strip()]

    def _transform_batch(self, texts, batch_size):
        # The model handles short sentences well but degrades on long inputs,
        # so each document is transliterated segment by segment and
        # reassembled with its original separators.
        split = [self._split_sentences(text) for text in texts]
        sentences = [parts[i] for parts, indices in split for i in indices]
        outputs = []
        for start in range(0, len(sentences), batch_size):
            outputs.extend(
                self._transliterate_sentences(sentences[start : start + batch_size])
            )
        outputs = iter(outputs)
        results = []
        for parts, indices in split:
            for i in indices:
                parts[i] = next(outputs)
            results.append("".join(parts))
        return results

    def _max_new_tokens(self, prefixed: list[str]) -> int:
        if self.max_new_tokens is not None:
            return self.max_new_tokens
        # Byte-level output is about as long as its input; leave ample headroom.
        return 2 * max(len(text.encode("utf-8")) for text in prefixed) + 16

    def _transliterate_sentences(self, texts):
        if not texts:
            return []
        # The legacy encoder dynamically quantizes across all input rows. Even
        # equal-length distinct texts can change each other's output. Encode
        # identical inputs together; batch the expensive decoder independently.
        prefixed = [f"{self._direction}: {text.strip()}" for text in texts]
        groups = defaultdict(list)
        for i, text in enumerate(prefixed):
            groups[text].append(i)
        states, masks = [None] * len(texts), [None] * len(texts)
        for indices in groups.values():
            encoded, attention = self.encoder.encode_batch(
                [prefixed[i] for i in indices]
            )
            for row, document in enumerate(indices):
                states[document] = encoded[row]
                masks[document] = attention[row]
        length = max(len(mask) for mask in masks)
        encoded = np.stack(
            [np.pad(state, ((0, length - len(state)), (0, 0))) for state in states]
        )
        mask = np.stack([np.pad(mask, (0, length - len(mask))) for mask in masks])
        limit = self._max_new_tokens(prefixed)
        sequences = self.decoder.decode_batch(encoded, mask, self.num_beams, limit)
        if any(len(ids) >= limit for ids in sequences):
            warnings.warn(
                f"Transliteration reached max_new_tokens={limit} and was truncated; "
                "increase max_new_tokens or split the input into shorter sentences.",
                RuntimeWarning,
                stacklevel=3,
            )
        return [self.encoder.tokenizer.detokenize(ids) for ids in sequences]
